// Writes the credits section of README.md from src/data/credits.ts (names, URLs, licenses) and
// src/i18n/en/about.json (texts) – the same sources as the "About" dialog. Only the part between
// <!-- credits:start --> and <!-- credits:end --> is replaced.
// Runs before every build (npm "prebuild"); Node ≥ 22.18 loads the .ts file via type stripping.
import fs from 'node:fs';
import { CREDITS } from '../src/data/credits.ts';

const readmeUrl = new URL('../README.md', import.meta.url);
const text = JSON.parse(fs.readFileSync(new URL('../src/i18n/en/about.json', import.meta.url), 'utf8'));

const cell = (/** @type {string} */ value) => String(value).replace(/\|/g, '\\|');
const required = (/** @type {unknown} */ value, /** @type {string} */ key) => {
  if (typeof value !== 'string') throw new Error(`src/i18n/en/about.json: text "${key}" is missing`);
  return value;
};

const section = [
  '<!-- credits:start – generated by scripts/sync-readme.mjs from src/data/credits.ts and src/i18n/en/about.json, do not edit by hand -->',
  cell(required(text.openSource, 'openSource')),
  '',
  ...CREDITS.flatMap((group) => [
    `### ${required(text.groups?.[group.id], `groups.${group.id}`)}`,
    '',
    `| ${text.table.project} | ${text.table.purpose} | ${text.table.license} |`,
    '|---|---|---|',
    ...group.items.map((i) => {
      const purpose = required(text.purposes?.[i.id], `purposes.${i.id}`);
      const license = text.licenses?.[i.license] ?? i.license;
      return `| [${cell(i.name)}](${i.url}) | ${cell(purpose)} | ${cell(license)} |`;
    }),
    '',
  ]),
  '---',
  '',
  `<p align="center">${required(text.madeWith, 'madeWith')}</p>`,
  '<!-- credits:end -->',
].join('\n');

const readme = fs.readFileSync(readmeUrl, 'utf8');
const pattern = /<!-- credits:start[\s\S]*?<!-- credits:end -->/;
if (!pattern.test(readme)) throw new Error('README.md: markers <!-- credits:start --> … <!-- credits:end --> are missing');
const updated = readme.replace(pattern, () => section);
if (updated !== readme) {
  fs.writeFileSync(readmeUrl, updated);
  console.log('README.md: credits section updated from credits.ts + en/about.json');
}
