export type MethodKind = 'fx' | 'mod' | 'source';

/** Grobe Einordnung einer (nicht abbildbaren) Methode. */
export function methodKind(name: string): MethodKind {
  const n = canonical(name);
  if (FX.has(n)) return 'fx';
  if (MODIFIERS.has(n)) return 'mod';
  return 'source';
}

